export interface RoadTransportResult {
  url: string
}

/**
 * 随机生成道路运输证号，格式：省份简称 + 交运管 + 地市简称 + 字 + 12位数字 + 号，
 * 如 云交运管昆字530102797211号
 */
export function randomCertificateNo(): string {
  const province = sample(PROVINCES)
  const city = sample(CITIES[province] || [province])
  return `${province}交运管${city}字${randomDigits(12)}号`
}

export async function generateRoadTransport(
  plateNo: string,
  licenseNo: string,
  certificateNo: string,
): Promise<RoadTransportResult> {
  const img = await loadImage(TEMPLATE)
  const canvas = document.createElement('canvas')
  canvas.width = img.width
  canvas.height = img.height
  const ctx = canvas.getContext('2d')
  if (!ctx) throw new Error('无法创建 canvas 上下文')

  ctx.drawImage(img, 0, 0)
  // 道路运输证号字段 weight=400 匹配模板观感（细体）
  fillText(ctx, plateNo, PLATE, { weight: 400 })
  fillText(ctx, licenseNo, LICENSE, { weight: 400 })
  fillText(ctx, certificateNo, CERT_LINE, { weight: 400 })

  return { url: canvas.toDataURL('image/png') }
}
